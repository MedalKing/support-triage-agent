"""Read the saved eval reports in evals/results/, for the admin Evals page and the folder index.

Only the reports in evals/results/ and its dated subfolders count as current. Older runs, made
against a less strict eval, live in evals/results/archive/ and are not listed. Sampling files
(a list of runs rather than a report) are not reports either.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

RESULTS_DIR = Path(__file__).resolve().parent.parent / "evals" / "results"
DATE = re.compile(r"\d{4}-\d{2}-\d{2}")
TIME = re.compile(r"(?:^|-)(\d{2})(\d{2})-")  # "2026-11-26-1236-..." or, inside a dated folder, "1236-..."


def label(provider: str) -> str:
    """"claude:claude-haiku-5-5" -> "Haiku 5.5 only", "auto:..." -> "Auto (Haiku → Opus)"."""
    if provider.startswith("auto:"):
        return "Auto (Haiku → Opus)"
    model = provider.split(":", 1)[-1]
    m = re.fullmatch(r"claude-([a-z]+)-(\d+)-(\d+)", model)
    if m:
        return f"{m[1].capitalize()} {m[2]}.{m[3]} only"
    return model


def _reports(root: Path = RESULTS_DIR) -> list[Path]:
    paths = [p for p in root.rglob("*.json") if "archive" not in p.relative_to(root).parts]
    out = []
    for p in paths:
        try:
            if isinstance(json.loads(p.read_text(encoding="utf-8")), dict):
                out.append(p)
        except ValueError:
            continue
    return out


def _when(path: Path, root: Path) -> tuple[str, str]:
    """Date and time from the file or folder name ("2026-11-26", "12:36" or "")."""
    rel = path.relative_to(root).as_posix()
    date = DATE.search(rel)
    time = TIME.search(DATE.sub("", path.name, count=1))
    return (date[0] if date else ""), (f"{time[1]}:{time[2]}" if time else "")


def summary(path: Path, root: Path = RESULTS_DIR) -> dict[str, Any]:
    data = json.loads(path.read_text(encoding="utf-8"))
    date, time = _when(path, root)
    totals = data.get("totals") or {}
    n = data.get("total") or len(data.get("cases", []))
    return {
        "id": path.relative_to(root).as_posix(),
        "provider": data.get("provider", ""),
        "label": label(data.get("provider", "")),
        "date": date,
        "time": time,
        "prompt_cache": data.get("prompt_cache"),  # None in reports made before caching existed
        "passed": data.get("passed"),
        "total": n,
        "escalated": data.get("escalated"),
        "cost_per_ticket": round(totals["cost_usd"] / n, 4) if totals.get("cost_usd") is not None and n else None,
        "median_seconds": totals.get("median_seconds"),
        "cached_share": totals.get("cached_share"),
    }


def runs(root: Path = RESULTS_DIR) -> list[dict[str, Any]]:
    """Current reports, newest first."""
    rows = [summary(p, root) for p in _reports(root)]
    return sorted(rows, key=lambda r: (r["date"], r["time"], r["id"]), reverse=True)


def report(run_id: str, root: Path = RESULTS_DIR) -> dict[str, Any] | None:
    """One report by its id (its path under the results folder); None if it isn't a current report."""
    path = (root / run_id).resolve()
    if root.resolve() not in path.parents:
        return None  # outside the results folder
    if path not in [p.resolve() for p in _reports(root)]:
        return None
    return {**summary(path, root), "cases": json.loads(path.read_text(encoding="utf-8")).get("cases", [])}


def write_index(root: Path = RESULTS_DIR) -> Path:
    """evals/results/README.md: one line per current report, so the folder explains itself."""
    def money(v: float | None) -> str:
        return "–" if v is None else f"${v:.4f}"

    def cache(v: bool | None) -> str:
        return "–" if v is None else ("on" if v else "off")

    lines = [
        "# Eval results",
        "",
        "Generated by `evals/run_evals.py` after every run; don't edit by hand. Each file is one run of all",
        "the cases in `evals/cases.yaml`. Older runs, made against a less strict eval, are in `archive/`.",
        "The same list is on the demo's admin-only Evals page.",
        "",
        "| Run | When | Passed | Escalated | Cost per ticket | Median time | Prompt cache |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for r in runs(root):
        when = f"{r['date']} {r['time']}".strip()
        secs = "–" if r["median_seconds"] is None else f"{r['median_seconds']} s"
        lines.append(f"| [{r['label']}]({r['id']}) | {when} | {r['passed']}/{r['total']} | {r['escalated'] or 0} "
                     f"| {money(r['cost_per_ticket'])} | {secs} | {cache(r['prompt_cache'])} |")
    path = root / "README.md"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path
